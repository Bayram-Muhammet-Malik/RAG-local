#!/bin/sh
set -e
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" <<EOSQL
CREATE USER nextcloud WITH PASSWORD '$NEXTCLOUD_DB_PASSWORD';
CREATE DATABASE nextcloud OWNER nextcloud;
CREATE USER ai WITH PASSWORD '$AI_DB_PASSWORD';
CREATE DATABASE ai OWNER ai;
CREATE USER authelia WITH PASSWORD '$AUTHELIA_DB_PASSWORD';
CREATE DATABASE authelia OWNER authelia;
EOSQL
psql -v ON_ERROR_STOP=1 -U "$POSTGRES_USER" -d ai -c "CREATE EXTENSION IF NOT EXISTS vector;"